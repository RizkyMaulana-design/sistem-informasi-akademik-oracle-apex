-- Sistem Informasi Akademik | Membuat 10 tabel (urutan sesuai ketergantungan foreign key)
-- Jalankan di: Oracle APEX > SQL Workshop > SQL Scripts

CREATE TABLE PROGRAM_STUDI (
  KODE_PRODI VARCHAR2(10) PRIMARY KEY,
  NAMA_PRODI VARCHAR2(100) NOT NULL,
  JENJANG    VARCHAR2(10)
);

CREATE TABLE MAHASISWA (
  NIM            VARCHAR2(15) PRIMARY KEY,
  NAMA_MAHASISWA VARCHAR2(100) NOT NULL,
  JENIS_KELAMIN  CHAR(1),
  TANGGAL_LAHIR  DATE,
  ALAMAT         VARCHAR2(200),
  EMAIL          VARCHAR2(100),
  ANGKATAN       NUMBER(4),
  KODE_PRODI     VARCHAR2(10),
  FOREIGN KEY (KODE_PRODI) REFERENCES PROGRAM_STUDI(KODE_PRODI)
);

CREATE TABLE DOSEN (
  NIDN       VARCHAR2(20) PRIMARY KEY,
  NAMA_DOSEN VARCHAR2(100) NOT NULL,
  EMAIL      VARCHAR2(100),
  NO_HP      VARCHAR2(15),
  KODE_PRODI VARCHAR2(10),
  FOREIGN KEY (KODE_PRODI) REFERENCES PROGRAM_STUDI(KODE_PRODI)
);

CREATE TABLE MATA_KULIAH (
  KODE_MK    VARCHAR2(10) PRIMARY KEY,
  NAMA_MK    VARCHAR2(100) NOT NULL,
  SKS        NUMBER(2),
  SEMESTER   NUMBER(2),
  KODE_PRODI VARCHAR2(10),
  FOREIGN KEY (KODE_PRODI) REFERENCES PROGRAM_STUDI(KODE_PRODI)
);

CREATE TABLE TAHUN_AKADEMIK (
  ID_TA          VARCHAR2(10) PRIMARY KEY,
  TAHUN_AKADEMIK VARCHAR2(20),
  SEMESTER       VARCHAR2(10),
  STATUS         VARCHAR2(15)
);

CREATE TABLE RUANGAN (
  ID_RUANGAN   VARCHAR2(10) PRIMARY KEY,
  NAMA_RUANGAN VARCHAR2(50),
  KAPASITAS    NUMBER(4),
  LOKASI       VARCHAR2(100)
);

CREATE TABLE KELAS_PERKULIAHAN (
  ID_KELAS    VARCHAR2(10) PRIMARY KEY,
  KODE_MK     VARCHAR2(10),
  NIDN        VARCHAR2(20),
  ID_TA       VARCHAR2(10),
  ID_RUANGAN  VARCHAR2(10),
  HARI        VARCHAR2(15),
  JAM_MULAI   VARCHAR2(5),
  JAM_SELESAI VARCHAR2(5),
  FOREIGN KEY (KODE_MK)    REFERENCES MATA_KULIAH(KODE_MK),
  FOREIGN KEY (NIDN)       REFERENCES DOSEN(NIDN),
  FOREIGN KEY (ID_TA)      REFERENCES TAHUN_AKADEMIK(ID_TA),
  FOREIGN KEY (ID_RUANGAN) REFERENCES RUANGAN(ID_RUANGAN)
);

CREATE TABLE KRS (
  ID_KRS      VARCHAR2(10) PRIMARY KEY,
  NIM         VARCHAR2(15),
  ID_TA       VARCHAR2(10),
  TANGGAL_KRS DATE,
  FOREIGN KEY (NIM)   REFERENCES MAHASISWA(NIM),
  FOREIGN KEY (ID_TA) REFERENCES TAHUN_AKADEMIK(ID_TA)
);

CREATE TABLE DETAIL_KRS (
  ID_DETAIL VARCHAR2(10) PRIMARY KEY,
  ID_KRS    VARCHAR2(10),
  ID_KELAS  VARCHAR2(10),
  FOREIGN KEY (ID_KRS)   REFERENCES KRS(ID_KRS),
  FOREIGN KEY (ID_KELAS) REFERENCES KELAS_PERKULIAHAN(ID_KELAS),
  CONSTRAINT UQ_KRS_KELAS UNIQUE (ID_KRS, ID_KELAS)
);

CREATE TABLE NILAI (
  ID_NILAI    VARCHAR2(10) PRIMARY KEY,
  ID_DETAIL   VARCHAR2(10),
  NILAI_ANGKA NUMBER(5,2),
  NILAI_HURUF VARCHAR2(2),
  FOREIGN KEY (ID_DETAIL) REFERENCES DETAIL_KRS(ID_DETAIL)
);
