CREATE OR REPLACE VIEW VW_MAHASISWA_PRODI AS
SELECT M.NIM, M.NAMA_MAHASISWA, M.JENIS_KELAMIN, M.ANGKATAN,
       P.NAMA_PRODI, P.JENJANG
FROM MAHASISWA M
JOIN PROGRAM_STUDI P ON M.KODE_PRODI = P.KODE_PRODI;

CREATE OR REPLACE VIEW VW_JADWAL_KELAS AS
SELECT KP.ID_KELAS, MK.NAMA_MK, MK.SKS, D.NAMA_DOSEN,
       R.NAMA_RUANGAN, KP.HARI, KP.JAM_MULAI, KP.JAM_SELESAI
FROM KELAS_PERKULIAHAN KP
JOIN MATA_KULIAH MK ON KP.KODE_MK = MK.KODE_MK
JOIN DOSEN D        ON KP.NIDN = D.NIDN
JOIN RUANGAN R      ON KP.ID_RUANGAN = R.ID_RUANGAN;

CREATE OR REPLACE VIEW VW_KRS_MAHASISWA AS
SELECT M.NIM, M.NAMA_MAHASISWA, MK.NAMA_MK, MK.SKS,
       KP.HARI, KP.JAM_MULAI, KP.JAM_SELESAI
FROM KRS K
JOIN MAHASISWA M          ON K.NIM = M.NIM
JOIN DETAIL_KRS DK        ON K.ID_KRS = DK.ID_KRS
JOIN KELAS_PERKULIAHAN KP ON DK.ID_KELAS = KP.ID_KELAS
JOIN MATA_KULIAH MK       ON KP.KODE_MK = MK.KODE_MK;

CREATE OR REPLACE VIEW VW_NILAI_MAHASISWA AS
SELECT M.NIM, M.NAMA_MAHASISWA, MK.NAMA_MK, MK.SKS,
       N.NILAI_ANGKA, N.NILAI_HURUF
FROM NILAI N
JOIN DETAIL_KRS DK        ON N.ID_DETAIL = DK.ID_DETAIL
JOIN KRS K                ON DK.ID_KRS = K.ID_KRS
JOIN MAHASISWA M          ON K.NIM = M.NIM
JOIN KELAS_PERKULIAHAN KP ON DK.ID_KELAS = KP.ID_KELAS
JOIN MATA_KULIAH MK       ON KP.KODE_MK = MK.KODE_MK;

CREATE OR REPLACE VIEW VW_IPS_MAHASISWA AS
SELECT NIM, NAMA_MAHASISWA, SUM(SKS) AS TOTAL_SKS,
       ROUND(SUM(SKS * DECODE(NILAI_HURUF,'A',4,'B',3,'C',2,'D',1,0)) / SUM(SKS), 2) AS IPS
FROM VW_NILAI_MAHASISWA
GROUP BY NIM, NAMA_MAHASISWA;

CREATE OR REPLACE VIEW VW_JUMLAH_MHS_PRODI AS
SELECT P.NAMA_PRODI, COUNT(M.NIM) AS JUMLAH_MAHASISWA
FROM PROGRAM_STUDI P
LEFT JOIN MAHASISWA M ON P.KODE_PRODI = M.KODE_PRODI
GROUP BY P.NAMA_PRODI;
